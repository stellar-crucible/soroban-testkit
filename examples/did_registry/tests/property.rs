//! One crate per file: this suite drives the registry through
//! `soroban-testkit-generators`, whose job is handing a test the identities and
//! document shapes nobody writes by hand.
//!
//! The central property is the registry's security claim: **only the controller
//! of a DID may modify its document**. Every case generates an authorized
//! controller, an attacker, a rotation target and a document modification, and
//! asserts that the attacker's attempt changes nothing — then that the
//! controller's own change succeeds.
//!
//! Each case builds its own `Env`, so a case cannot inherit another case's
//! storage or ledger clock.

use proptest::prelude::*;
use soroban_sdk::testutils::{Address as _, Ledger as _};
use soroban_sdk::{Address, Env, String, Vec};
use soroban_testkit_example_did_registry::{DidRegistry, DidRegistryClient, ServiceEndpoint};
use soroban_testkit_generators::strategies::{account_address, address, contract_address};

/// A registry with mocked auth, so a case has to think only about the addresses
/// and documents it generates.
fn deployed(env: &Env) -> DidRegistryClient<'_> {
    env.mock_all_auths();
    let admin = Address::generate(env);
    let contract = env.register(DidRegistry, ());
    let client = DidRegistryClient::new(env, &contract);
    client.initialize(&admin);
    client
}

/// The DID for a generated key: `did:stellar:<hex of the 32 generated bytes>`.
fn did_for(env: &Env, bytes: &[u8; 32]) -> String {
    String::from_str(env, &format!("did:stellar:{}", hex(bytes)))
}

fn method_for(env: &Env, bytes: &[u8; 32]) -> String {
    String::from_str(env, &format!("did:stellar:{}#key-1", hex(bytes)))
}

fn hex(bytes: &[u8; 32]) -> std::string::String {
    let mut out = std::string::String::with_capacity(64);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

/// `count` unique service endpoints for `did`.
fn endpoints(env: &Env, did: &String, count: u32) -> Vec<ServiceEndpoint> {
    let mut list = Vec::new(env);
    for index in 0..count {
        list.push_back(ServiceEndpoint {
            id: String::from_str(env, &format!("{}#svc-{index}", did_text(did))),
            service_type: String::from_str(env, "LinkedDomains"),
            endpoint: String::from_str(env, &format!("https://example.com/{index}")),
        });
    }
    list
}

/// The text of a host `String`, for building fragments in the test's `std`
/// string type.
fn did_text(did: &String) -> std::string::String {
    let bytes = did.to_bytes();
    let mut out = std::string::String::new();
    for index in 0..bytes.len() {
        out.push(bytes.get(index).unwrap() as char);
    }
    out
}

proptest! {
    // A case registers a contract and runs several calls, which is far more
    // work than a case over plain numbers. Fewer cases keeps the file quick
    // enough to run on every `cargo test`.
    #![proptest_config(ProptestConfig::with_cases(32))]

    #[test]
    fn only_an_authorized_controller_can_modify_a_did_document(
        seed in account_address(),
        attacker in contract_address(),
        rotation in account_address(),
        operation in 0u8..3,
        endpoint_count in 0u32..=3,
    ) {
        let env = Env::default();
        let controller = seed.to_address(&env);
        let attacker = attacker.to_address(&env);
        let rotation = rotation.to_address(&env);
        prop_assume!(attacker != controller);
        prop_assume!(rotation != controller);

        let client = deployed(&env);
        let did = did_for(&env, seed.as_bytes());
        let original = client.register_did(
            &controller,
            &did,
            &method_for(&env, seed.as_bytes()),
            &endpoints(&env, &did, endpoint_count),
        );

        // Every generated operation is one an authorized controller could
        // perform; the point is that an unauthorized caller cannot.
        let refused = match operation {
            0 => client
                .try_rotate_controller(&did, &attacker, &rotation)
                .is_err(),
            1 => client
                .try_set_service_endpoints(&did, &attacker, &endpoints(&env, &did, endpoint_count))
                .is_err(),
            _ => client
                .try_set_service_endpoints(&did, &attacker, &Vec::new(&env))
                .is_err(),
        };
        prop_assert!(refused, "the attacker's operation {operation} was accepted");

        // The failed operation changed nothing: same document, same controller,
        // same version, same endpoints.
        prop_assert_eq!(client.resolve_did(&did), Some(original.clone()));
        prop_assert_eq!(client.controller_of(&did), Some(controller.clone()));
        prop_assert_eq!(client.document_version(&did), Some(1));
        prop_assert_eq!(original.services.len(), endpoint_count);

        // Positive half: the same operation, signed by the controller, is
        // permitted and is the only thing that moves the version.
        let updated = client.rotate_controller(&did, &controller, &rotation);
        prop_assert_eq!(updated.controller.clone(), rotation.clone());
        prop_assert_eq!(updated.verification_method.controller, rotation.clone());
        prop_assert_eq!(updated.version, 2);
        prop_assert_eq!(updated.services, original.services);
        prop_assert_eq!(client.document_version(&did), Some(2));
    }

    #[test]
    fn an_authorized_controller_can_replace_its_service_endpoints(
        seed in account_address(),
        count in 0u32..=4,
        replacement in 0u32..=4,
    ) {
        let env = Env::default();
        let controller = seed.to_address(&env);
        let client = deployed(&env);
        let did = did_for(&env, seed.as_bytes());
        let registered = client.register_did(
            &controller,
            &did,
            &method_for(&env, seed.as_bytes()),
            &endpoints(&env, &did, count),
        );

        let replaced = client.set_service_endpoints(
            &did,
            &controller,
            &endpoints(&env, &did, replacement),
        );

        prop_assert_eq!(replaced.services.len(), replacement);
        prop_assert_eq!(replaced.controller.clone(), controller);
        prop_assert_eq!(replaced.version, registered.version + 1);
        // Replacing is a replacement, not an append: the count is exactly what
        // the controller submitted.
        prop_assert_eq!(client.resolve_did(&did).unwrap().services.len(), replacement);
    }

    #[test]
    fn a_registered_identifier_resolves_to_what_was_registered(seed in address()) {
        let env = Env::default();
        let controller = seed.to_address(&env);
        let client = deployed(&env);
        let did = did_for(&env, seed.as_bytes());
        let method = method_for(&env, seed.as_bytes());

        let document = client.register_did(
            &controller,
            &did,
            &method,
            &endpoints(&env, &did, 1),
        );

        prop_assert_eq!(document.id.clone(), did.clone());
        prop_assert_eq!(document.verification_method.id.clone(), method.clone());
        prop_assert_eq!(client.resolve_did(&did), Some(document));
        prop_assert_eq!(client.controller_of(&did), Some(controller));
    }

    #[test]
    fn both_soroban_address_formats_are_accepted_as_controllers(seed in address()) {
        let env = Env::default();
        let controller = seed.to_address(&env);
        let client = deployed(&env);
        let did = did_for(&env, seed.as_bytes());

        // `address()` generates account and contract addresses: the registry
        // treats control the same whichever form the controller has.
        let document = client.register_did(
            &controller,
            &did,
            &method_for(&env, seed.as_bytes()),
            &Vec::new(&env),
        );

        prop_assert_eq!(document.controller, controller);
    }

    #[test]
    fn generated_identifiers_outside_the_method_are_refused(
        text in prop_oneof![
            "did:example:[a-z]{3,8}",
            "DID:stellar:[a-z]{3,8}",
            "did:stellar:[a-z]{1,8} [a-z]{1,8}",
            "did:stellar:",
        ],
    ) {
        let env = Env::default();
        let client = deployed(&env);
        let controller = Address::generate(&env);

        // The identifier validation runs before anything is written, so a
        // generated DID that is not `did:stellar:<id>` can never register.
        prop_assert!(client
            .try_register_did(
                &controller,
                &String::from_str(&env, &text),
                &String::from_str(&env, "did:stellar:alice#key-1"),
                &Vec::new(&env),
            )
            .is_err());
        prop_assert!(client
            .resolve_did(&String::from_str(&env, &text))
            .is_none());
    }

    #[test]
    fn a_second_registration_of_the_same_identifier_is_always_refused(
        seed in account_address(),
        other in contract_address(),
    ) {
        let env = Env::default();
        let controller = seed.to_address(&env);
        let other = other.to_address(&env);
        prop_assume!(controller != other);

        let client = deployed(&env);
        let did = did_for(&env, seed.as_bytes());
        let document = client.register_did(
            &controller,
            &did,
            &method_for(&env, seed.as_bytes()),
            &Vec::new(&env),
        );

        prop_assert!(client
            .try_register_did(&other, &did, &method_for(&env, seed.as_bytes()), &Vec::new(&env))
            .is_err());
        // A refused takeover leaves the first controller in place.
        prop_assert_eq!(client.resolve_did(&did), Some(document));
    }

    #[test]
    fn an_endpoint_list_beyond_the_cap_is_refused(extra in 1u32..=4) {
        let env = Env::default();
        let controller = Address::generate(&env);
        let client = deployed(&env);
        let did = did_for(&env, &[7u8; 32]);

        // The cap is eight; ask for eight plus `extra` and nothing registers.
        prop_assert!(client
            .try_register_did(
                &controller,
                &did,
                &String::from_str(&env, "did:stellar:0707070707070707070707070707070707070707070707070707070707070707#key-1"),
                &endpoints(&env, &did, 8 + extra),
            )
            .is_err());
        prop_assert!(client.resolve_did(&did).is_none());
    }

    #[test]
    fn revoking_twice_is_refused_and_keeps_the_first_timestamp(extra in 0u64..1_000) {
        let env = Env::default();
        let client = deployed(&env);
        let controller = Address::generate(&env);
        let issuer = Address::generate(&env);
        let did = did_for(&env, &[3u8; 32]);
        client.register_did(
            &controller,
            &did,
            &String::from_str(&env, "did:stellar:0303030303030303030303030303030303030303030303030303030303030303#key-1"),
            &Vec::new(&env),
        );
        let credential_id = String::from_str(&env, "vc:alice:degree:1");
        client.register_credential(&issuer, &credential_id, &did);

        env.ledger().set_timestamp(1_700_000_000);
        let revoked = client.revoke_credential(&issuer, &credential_id);
        prop_assert!(revoked.revoked);
        prop_assert_eq!(revoked.revoked_at, 1_700_000_000);

        // A repeat revocation is refused rather than silently re-timestamped:
        // the status an auditor reads stays the moment it was first revoked.
        env.ledger().set_timestamp(1_700_000_000 + extra);
        prop_assert!(client
            .try_revoke_credential(&issuer, &credential_id)
            .is_err());
        prop_assert_eq!(
            client.credential(&credential_id).map(|credential| credential.revoked_at),
            Some(1_700_000_000)
        );
        prop_assert_eq!(client.is_revoked(&credential_id), Some(true));
    }

    #[test]
    fn an_unknown_credential_is_reported_as_unknown_not_as_active(
        credential_id in "[a-z0-9:._-]{4,24}",
    ) {
        let env = Env::default();
        let client = deployed(&env);
        let credential_id = String::from_str(&env, &credential_id);

        // `None` is the registry never having seen it, which a verifier must
        // not read as `Some(false)`.
        prop_assert_eq!(client.is_revoked(&credential_id), None);
        prop_assert_eq!(client.credential(&credential_id), None);
        prop_assert!(client
            .try_revoke_credential(&Address::generate(&env), &credential_id)
            .is_err());
    }
}
