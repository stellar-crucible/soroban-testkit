//! Strategies for XDR-compatible Soroban values.
//!
//! Contract interfaces take `Symbol`, `String`, `Bytes`, `Vec<T>` and
//! `Map<K, V>` arguments, often nested. This module generates all of them with
//! configurable size bounds, composes them into nested shapes, and builds
//! arbitrary `Val` trees whose depth is capped so recursive generation cannot
//! overflow the stack or the host's object limits.
//!
//! There are two layers:
//!
//! - **Typed strategies** — [`xdr_symbol`], [`xdr_string`], [`xdr_bytes`],
//!   [`xdr_vec`] and [`xdr_map`] — produce host values owned by an [`Env`] and
//!   compose like any other strategy:
//!
//!   ```
//!   use proptest::prelude::*;
//!   use proptest::strategy::ValueTree;
//!   use proptest::test_runner::TestRunner;
//!   use soroban_sdk::Env;
//!   use soroban_testkit_generators::xdr::{xdr_map, xdr_symbol, xdr_vec};
//!
//!   let env = Env::default();
//!   // Map<Symbol, Vec<Symbol>>, at most 4 entries of at most 3 symbols each.
//!   let strategy = xdr_map(
//!       &env,
//!       xdr_symbol(&env, 8),
//!       xdr_vec(&env, xdr_symbol(&env, 8), 3),
//!       4,
//!   );
//!   let mut runner = TestRunner::default();
//!   let map = strategy.new_tree(&mut runner).unwrap().current();
//!   assert!(map.len() <= 4);
//!   ```
//!
//! - **Untyped trees** — [`xdr_value`] and [`xdr_val`] — produce an
//!   [`XdrValue`] description, or the `Val` built from it, mixing every
//!   supported kind under the limits of an [`XdrBounds`].

use proptest::prelude::*;
use proptest::string::string_regex;
use soroban_sdk::{Bytes, Env, IntoVal, Map, String, Symbol, TryFromVal, Val, Vec};

/// Longest symbol the host accepts.
pub const MAX_SYMBOL_LEN: usize = 32;

/// Size and depth limits for generated XDR values.
///
/// Every limit is inclusive. Lengths of strings and bytes are counted in
/// bytes; collection limits count elements (for a vector) or entries (for a
/// map). `max_depth` counts container levels: `0` generates scalars only, `1`
/// allows a vector or map of scalars, `2` a vector of vectors, and so on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct XdrBounds {
    /// Longest generated symbol, clamped to [`MAX_SYMBOL_LEN`].
    pub max_symbol_len: usize,
    /// Longest generated string, in bytes.
    pub max_string_len: usize,
    /// Longest generated byte array.
    pub max_bytes_len: usize,
    /// Most elements in a generated vector or entries in a generated map.
    pub max_collection_len: usize,
    /// Deepest container nesting a generated tree may have.
    pub max_depth: u32,
}

impl Default for XdrBounds {
    fn default() -> Self {
        Self {
            max_symbol_len: MAX_SYMBOL_LEN,
            max_string_len: 64,
            max_bytes_len: 64,
            max_collection_len: 8,
            max_depth: 3,
        }
    }
}

impl XdrBounds {
    /// Bounds that generate scalars only.
    pub fn scalars() -> Self {
        Self {
            max_depth: 0,
            ..Self::default()
        }
    }

    /// Set the longest generated symbol.
    pub fn with_max_symbol_len(mut self, len: usize) -> Self {
        self.max_symbol_len = len.min(MAX_SYMBOL_LEN);
        self
    }

    /// Set the longest generated string.
    pub fn with_max_string_len(mut self, len: usize) -> Self {
        self.max_string_len = len;
        self
    }

    /// Set the longest generated byte array.
    pub fn with_max_bytes_len(mut self, len: usize) -> Self {
        self.max_bytes_len = len;
        self
    }

    /// Set the largest generated vector or map.
    pub fn with_max_collection_len(mut self, len: usize) -> Self {
        self.max_collection_len = len;
        self
    }

    /// Set the deepest container nesting.
    pub fn with_max_depth(mut self, depth: u32) -> Self {
        self.max_depth = depth;
        self
    }
}

/// An environment-independent description of an XDR value.
///
/// Generating a description first keeps shrinking cheap and lets a failing
/// case print as plain data. Turn it into a host value with
/// [`XdrValue::to_val`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum XdrValue {
    /// `ScVal::Void`.
    Void,
    /// `ScVal::Bool`.
    Bool(bool),
    /// `ScVal::U32`.
    U32(u32),
    /// `ScVal::I32`.
    I32(i32),
    /// `ScVal::U64`.
    U64(u64),
    /// `ScVal::I64`.
    I64(i64),
    /// `ScVal::U128`.
    U128(u128),
    /// `ScVal::I128`.
    I128(i128),
    /// `ScVal::Symbol`, always made of `[a-zA-Z0-9_]`.
    Symbol(std::string::String),
    /// `ScVal::String`, printable ASCII.
    String(std::string::String),
    /// `ScVal::Bytes`.
    Bytes(std::vec::Vec<u8>),
    /// `ScVal::Vec`.
    Vec(std::vec::Vec<XdrValue>),
    /// `ScVal::Map` with unique keys, in generation order.
    Map(std::vec::Vec<(XdrValue, XdrValue)>),
}

impl XdrValue {
    /// Container nesting depth: `0` for a scalar.
    pub fn depth(&self) -> u32 {
        match self {
            XdrValue::Vec(items) => 1 + items.iter().map(XdrValue::depth).max().unwrap_or(0),
            XdrValue::Map(entries) => {
                1 + entries
                    .iter()
                    .map(|(key, value)| key.depth().max(value.depth()))
                    .max()
                    .unwrap_or(0)
            }
            _ => 0,
        }
    }

    /// Largest vector length or map size anywhere in the tree.
    pub fn max_collection_len(&self) -> usize {
        match self {
            XdrValue::Vec(items) => items
                .iter()
                .map(XdrValue::max_collection_len)
                .max()
                .unwrap_or(0)
                .max(items.len()),
            XdrValue::Map(entries) => entries
                .iter()
                .map(|(key, value)| key.max_collection_len().max(value.max_collection_len()))
                .max()
                .unwrap_or(0)
                .max(entries.len()),
            _ => 0,
        }
    }

    /// Build the host value this description stands for.
    pub fn to_val(&self, env: &Env) -> Val {
        match self {
            XdrValue::Void => ().into_val(env),
            XdrValue::Bool(value) => value.into_val(env),
            XdrValue::U32(value) => value.into_val(env),
            XdrValue::I32(value) => value.into_val(env),
            XdrValue::U64(value) => value.into_val(env),
            XdrValue::I64(value) => value.into_val(env),
            XdrValue::U128(value) => value.into_val(env),
            XdrValue::I128(value) => value.into_val(env),
            XdrValue::Symbol(value) => Symbol::new(env, value).into_val(env),
            XdrValue::String(value) => String::from_str(env, value).into_val(env),
            XdrValue::Bytes(value) => Bytes::from_slice(env, value).into_val(env),
            XdrValue::Vec(items) => {
                let mut vec: Vec<Val> = Vec::new(env);
                for item in items {
                    vec.push_back(item.to_val(env));
                }
                vec.into_val(env)
            }
            XdrValue::Map(entries) => {
                let mut map: Map<Val, Val> = Map::new(env);
                for (key, value) in entries {
                    map.set(key.to_val(env), value.to_val(env));
                }
                map.into_val(env)
            }
        }
    }
}

fn symbol_chars(max_len: usize) -> impl Strategy<Value = std::string::String> {
    let max_len = max_len.min(MAX_SYMBOL_LEN);
    string_regex(&format!("[a-zA-Z0-9_]{{0,{max_len}}}")).expect("a valid symbol regex")
}

fn ascii_chars(max_len: usize) -> impl Strategy<Value = std::string::String> {
    string_regex(&format!("[ -~]{{0,{max_len}}}")).expect("a valid printable-ASCII regex")
}

/// Generates a [`Symbol`] of at most `max_len` characters from `[a-zA-Z0-9_]`.
///
/// `max_len` is clamped to [`MAX_SYMBOL_LEN`]. Shrinks towards the empty
/// symbol.
pub fn xdr_symbol(env: &Env, max_len: usize) -> impl Strategy<Value = Symbol> {
    let env = env.clone();
    symbol_chars(max_len).prop_map(move |chars| Symbol::new(&env, &chars))
}

/// Generates a [`String`] of at most `max_len` printable ASCII bytes.
pub fn xdr_string(env: &Env, max_len: usize) -> impl Strategy<Value = String> {
    let env = env.clone();
    ascii_chars(max_len).prop_map(move |chars| String::from_str(&env, &chars))
}

/// Generates [`Bytes`] of at most `max_len` bytes.
pub fn xdr_bytes(env: &Env, max_len: usize) -> impl Strategy<Value = Bytes> {
    let env = env.clone();
    prop::collection::vec(any::<u8>(), 0..=max_len)
        .prop_map(move |bytes| Bytes::from_slice(&env, &bytes))
}

/// Generates a host [`Vec<T>`] of at most `max_len` elements drawn from
/// `element`.
///
/// `element` can itself be any XDR strategy, so `xdr_vec(&env,
/// xdr_vec(&env, xdr_symbol(&env, 8), 2), 3)` generates a `Vec<Vec<Symbol>>`.
pub fn xdr_vec<S>(env: &Env, element: S, max_len: usize) -> impl Strategy<Value = Vec<S::Value>>
where
    S: Strategy,
    S::Value: IntoVal<Env, Val> + TryFromVal<Env, Val> + Clone,
{
    let env = env.clone();
    prop::collection::vec(element, 0..=max_len).prop_map(move |items| {
        let mut vec = Vec::new(&env);
        for item in items {
            vec.push_back(item);
        }
        vec
    })
}

/// Generates a host [`Map<K, V>`] of at most `max_len` entries.
///
/// Duplicate keys collapse, as they do on chain, so a map can come out with
/// fewer entries than were drawn.
pub fn xdr_map<KS, VS>(
    env: &Env,
    key: KS,
    value: VS,
    max_len: usize,
) -> impl Strategy<Value = Map<KS::Value, VS::Value>>
where
    KS: Strategy,
    VS: Strategy,
    KS::Value: IntoVal<Env, Val> + TryFromVal<Env, Val> + Clone,
    VS::Value: IntoVal<Env, Val> + TryFromVal<Env, Val> + Clone,
{
    let env = env.clone();
    prop::collection::vec((key, value), 0..=max_len).prop_map(move |entries| {
        let mut map = Map::new(&env);
        for (key, value) in entries {
            map.set(key, value);
        }
        map
    })
}

fn scalar_value(bounds: XdrBounds) -> BoxedStrategy<XdrValue> {
    prop_oneof![
        Just(XdrValue::Void),
        any::<bool>().prop_map(XdrValue::Bool),
        any::<u32>().prop_map(XdrValue::U32),
        any::<i32>().prop_map(XdrValue::I32),
        any::<u64>().prop_map(XdrValue::U64),
        any::<i64>().prop_map(XdrValue::I64),
        any::<u128>().prop_map(XdrValue::U128),
        any::<i128>().prop_map(XdrValue::I128),
        symbol_chars(bounds.max_symbol_len).prop_map(XdrValue::Symbol),
        ascii_chars(bounds.max_string_len).prop_map(XdrValue::String),
        prop::collection::vec(any::<u8>(), 0..=bounds.max_bytes_len).prop_map(XdrValue::Bytes),
    ]
    .boxed()
}

/// Generates an [`XdrValue`] tree inside `bounds`.
///
/// Leaves are drawn from every scalar kind plus symbols, strings and bytes;
/// containers are vectors and maps (with scalar keys) of at most
/// `bounds.max_collection_len` entries, nested at most `bounds.max_depth`
/// levels. Shrinking collapses containers towards scalars and scalars towards
/// `Void`.
pub fn xdr_value(bounds: XdrBounds) -> impl Strategy<Value = XdrValue> {
    let leaf = scalar_value(bounds);
    let max_len = bounds.max_collection_len;
    let desired_size = (max_len.max(1) as u32).saturating_pow(bounds.max_depth.min(4));
    let key = scalar_value(bounds);
    leaf.prop_recursive(
        bounds.max_depth,
        desired_size.max(1),
        max_len.max(1) as u32,
        move |inner| {
            prop_oneof![
                prop::collection::vec(inner.clone(), 0..=max_len).prop_map(XdrValue::Vec),
                prop::collection::vec((key.clone(), inner), 0..=max_len).prop_map(|entries| {
                    let mut unique: std::vec::Vec<(XdrValue, XdrValue)> =
                        std::vec::Vec::with_capacity(entries.len());
                    for (key, value) in entries {
                        if !unique.iter().any(|(seen, _)| *seen == key) {
                            unique.push((key, value));
                        }
                    }
                    XdrValue::Map(unique)
                }),
            ]
        },
    )
}

/// Generates a host [`Val`] built from an [`xdr_value`] tree.
pub fn xdr_val(env: &Env, bounds: XdrBounds) -> impl Strategy<Value = Val> {
    let env = env.clone();
    xdr_value(bounds).prop_map(move |value| value.to_val(&env))
}

#[cfg(test)]
mod tests {
    use super::*;
    use proptest::strategy::ValueTree;
    use soroban_sdk::xdr::ScVal;

    proptest! {
        #[test]
        fn trees_respect_depth_and_size_bounds(
            value in xdr_value(XdrBounds::default().with_max_depth(2).with_max_collection_len(3))
        ) {
            prop_assert!(value.depth() <= 2);
            prop_assert!(value.max_collection_len() <= 3);
        }

        #[test]
        fn scalar_bounds_never_generate_containers(value in xdr_value(XdrBounds::scalars())) {
            prop_assert_eq!(value.depth(), 0);
        }

        #[test]
        fn generated_vals_round_trip_through_xdr(value in xdr_value(XdrBounds::default())) {
            let env = Env::default();
            let val = value.to_val(&env);
            let scval = ScVal::try_from_val(&env, &val);
            prop_assert!(scval.is_ok());
        }

        #[test]
        fn strings_and_bytes_respect_their_bounds(
            (string, bytes) in {
                let env = Env::default();
                (xdr_string(&env, 12), xdr_bytes(&env, 9))
            }
        ) {
            prop_assert!(string.len() <= 12);
            prop_assert!(bytes.len() <= 9);
        }
    }

    #[test]
    fn symbols_respect_their_length_bound() {
        let env = Env::default();
        let mut runner = proptest::test_runner::TestRunner::default();
        for len in [0usize, 1, 5, 32, 40] {
            let strategy = xdr_symbol(&env, len);
            for _ in 0..16 {
                let symbol = strategy.new_tree(&mut runner).unwrap().current();
                assert!(symbol.to_string().len() <= len.min(MAX_SYMBOL_LEN));
            }
        }
    }

    #[test]
    fn nested_strategies_compose() {
        let env = Env::default();
        let strategy = xdr_map(
            &env,
            xdr_symbol(&env, 6),
            xdr_vec(&env, xdr_symbol(&env, 6), 3),
            4,
        );
        let mut runner = proptest::test_runner::TestRunner::default();
        for _ in 0..32 {
            let map = strategy.new_tree(&mut runner).unwrap().current();
            assert!(map.len() <= 4);
            for (_, inner) in map.iter() {
                assert!(inner.len() <= 3);
            }
        }
    }

    #[test]
    fn deep_bounds_do_not_overflow_the_stack() {
        let env = Env::default();
        let strategy = xdr_val(
            &env,
            XdrBounds::default()
                .with_max_depth(8)
                .with_max_collection_len(2),
        );
        let mut runner = proptest::test_runner::TestRunner::default();
        for _ in 0..16 {
            let _ = strategy.new_tree(&mut runner).unwrap().current();
        }
    }
}
