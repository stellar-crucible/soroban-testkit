//! Declarative in-memory mock contracts for third-party dependencies.
//!
//! A unit test that exercises a contract calling an external protocol (an
//! oracle, a DEX, a token) usually needs a stand-in for that protocol. Writing
//! one by hand means defining another `#[contract]`, giving it the right
//! signatures, and wiring its storage — boilerplate that has nothing to do
//! with the behaviour under test.
//!
//! This module lets a test declare the mock's **interface** once with
//! [`mock_contract`], then configure **behaviour** per test with
//! [`MockContractBuilder`]:
//!
//! ```ignore
//! mock_contract! {
//!     pub RateOracle {
//!         fn get_rate(asset: Address) -> i128;
//!     }
//! }
//!
//! let oracle = MockContractBuilder::<RateOracle>::new(&ctx.env)
//!     .expect_call("get_rate", |_env, _args| 1_500i128)
//!     .times(2)
//!     .build();
//!
//! consumer_client.trade(&oracle.address(), &usdc);
//! oracle.assert_expectations();
//! ```
//!
//! # Why the interface has to be declared
//!
//! A Soroban host resolves an invocation to an *exported function symbol*
//! before any contract code runs. There is no entry point that receives the
//! function name as a value, so the SDK cannot expose a contract whose
//! exported functions are decided at runtime. [`mock_contract`] therefore
//! generates a real contract at compile time from a one-line-per-function
//! declaration, and the runtime configuration happens *inside* those generated
//! functions: they forward the name and the encoded arguments to the
//! expectation registered by the builder.
//!
//! # Scope
//!
//! Mocks are registered in a thread-local registry keyed by the contract
//! address, so they work with `#[test]` functions (which run on their own
//! threads) but not across threads or in a wasm build. The registry entry is
//! removed when the [`MockContract`] is dropped.

use std::cell::{Cell, RefCell};
use std::marker::PhantomData;
use std::rc::Rc;

use soroban_sdk::{Address, Env, IntoVal, TryFromVal, Val};

type Handler = Box<dyn Fn(&Env, &[Val]) -> Result<Val, String>>;

thread_local! {
    /// Live mocks on this thread, keyed by the address they were registered at.
    static MOCKS: RefCell<Vec<(Address, Rc<RefCell<MockSpec>>)>> = const { RefCell::new(Vec::new()) };
}

/// Implemented by the contract generated by [`mock_contract`] so the builder
/// can register it on the [`Env`].
pub trait MockContractType {
    /// Registers the generated contract and returns its address.
    #[doc(hidden)]
    fn register_mock(env: &Env) -> Address;
}

struct Expectation {
    name: String,
    min_calls: u32,
    max_calls: Option<u32>,
    calls: Cell<u32>,
    handler: Handler,
}

struct MockSpec {
    expectations: Vec<Expectation>,
}

impl MockSpec {
    fn find_mut(&mut self, name: &str) -> Option<&mut Expectation> {
        self.expectations.iter_mut().find(|e| e.name == name)
    }

    fn invoke(&mut self, env: &Env, name: &str, args: &[Val]) -> Result<Val, String> {
        let expected = self
            .expectations
            .iter()
            .map(|e| e.name.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let expectation = self.find_mut(name).ok_or_else(|| {
            format!("mock contract: unexpected call to `{name}` (configured functions: {expected})")
        })?;

        let calls = expectation.calls.get();
        if let Some(max) = expectation.max_calls {
            if calls >= max {
                return Err(format!(
                    "mock contract: `{name}` called {} time(s) but expected at most {max}",
                    calls + 1
                ));
            }
        }
        // A rejected call is not recorded, so the expectation can still be
        // verified (and a `never()` expectation stays at zero).
        expectation.calls.set(calls + 1);

        (expectation.handler)(env, args)
    }

    fn assert_expectations(&self) {
        let mut failures = Vec::new();
        for expectation in &self.expectations {
            let calls = expectation.calls.get();
            if let Some(max) = expectation.max_calls {
                if calls > max {
                    failures.push(format!(
                        "`{}` called {calls} time(s), expected at most {max}",
                        expectation.name
                    ));
                    continue;
                }
            }
            if calls < expectation.min_calls {
                failures.push(format!(
                    "`{}` called {calls} time(s), expected at least {}",
                    expectation.name, expectation.min_calls
                ));
            }
        }
        if !failures.is_empty() {
            panic!(
                "mock contract expectations not met: {}",
                failures.join("; ")
            );
        }
    }
}

/// Builds the behaviour of a mock contract generated by [`mock_contract`].
///
/// The interface is fixed at compile time (`MockContractBuilder::<MyMock>::new`);
/// everything else — return values, argument assertions, call counts — is
/// configured at runtime and verified by [`MockContract::assert_expectations`]
/// or when the mock is dropped.
///
/// Expectations default to "called exactly once". Chain [`times`](Self::times),
/// [`at_least`](Self::at_least) or [`never`](Self::never) after an `expect_*`
/// call to change that.
pub struct MockContractBuilder<T: MockContractType> {
    env: Env,
    spec: Rc<RefCell<MockSpec>>,
    last: Option<usize>,
    _contract: PhantomData<fn() -> T>,
}

impl<T: MockContractType> MockContractBuilder<T> {
    /// Starts a mock for `T`, the contract generated by [`mock_contract`].
    pub fn new(env: &Env) -> Self {
        Self {
            env: env.clone(),
            spec: Rc::new(RefCell::new(MockSpec {
                expectations: Vec::new(),
            })),
            last: None,
            _contract: PhantomData,
        }
    }

    /// Expects `name` to be called, returning whatever `handler` produces.
    ///
    /// The handler receives the invocation's [`Env`] and its arguments encoded
    /// as [`Val`]s, in declaration order. Use [`arg`] to decode them.
    pub fn expect_call<F, R>(self, name: impl Into<String>, handler: F) -> Self
    where
        F: Fn(&Env, &[Val]) -> R + 'static,
        R: IntoVal<Env, Val>,
    {
        self.push(
            name.into(),
            Box::new(move |env, args| Ok(handler(env, args).into_val(env))),
        )
    }

    /// Expects `name` to be called and simulates a contract panic with
    /// `message`, which the caller observes as a failed invocation.
    pub fn expect_panic(self, name: impl Into<String>, message: impl Into<String>) -> Self {
        let message = message.into();
        self.push(
            name.into(),
            Box::new(move |_env, _args| Err(format!("mock contract: {message}"))),
        )
    }

    /// Requires exactly `n` calls to the most recent expectation.
    pub fn times(self, n: u32) -> Self {
        self.with_last(|expectation| {
            expectation.min_calls = n;
            expectation.max_calls = Some(n);
        })
    }

    /// Requires at least `n` calls to the most recent expectation.
    pub fn at_least(self, n: u32) -> Self {
        self.with_last(|expectation| {
            expectation.min_calls = n;
            expectation.max_calls = None;
        })
    }

    /// Requires the most recent expectation never to be called.
    pub fn never(self) -> Self {
        self.with_last(|expectation| {
            expectation.min_calls = 0;
            expectation.max_calls = Some(0);
        })
    }

    /// Registers the mock contract on the [`Env`] and returns a handle to it.
    pub fn build(self) -> MockContract {
        let address = T::register_mock(&self.env);
        MOCKS.with(|mocks| {
            mocks
                .borrow_mut()
                .push((address.clone(), Rc::clone(&self.spec)));
        });
        MockContract {
            address,
            spec: self.spec,
            verified: Cell::new(false),
        }
    }

    fn push(self, name: String, handler: Handler) -> Self {
        let mut spec = self.spec.borrow_mut();
        spec.expectations.push(Expectation {
            name,
            min_calls: 1,
            max_calls: Some(1),
            calls: Cell::new(0),
            handler,
        });
        let last = spec.expectations.len() - 1;
        drop(spec);
        Self {
            last: Some(last),
            ..self
        }
    }

    fn with_last(self, update: impl FnOnce(&mut Expectation)) -> Self {
        let Some(index) = self.last else {
            panic!("call expect_call or expect_panic before configuring call counts");
        };
        update(&mut self.spec.borrow_mut().expectations[index]);
        self
    }
}

/// A registered mock contract.
pub struct MockContract {
    address: Address,
    spec: Rc<RefCell<MockSpec>>,
    verified: Cell<bool>,
}

impl MockContract {
    /// The address to pass to the contract under test.
    pub fn address(&self) -> Address {
        self.address.clone()
    }

    /// How many times `name` has been called so far.
    pub fn calls(&self, name: &str) -> u32 {
        self.spec
            .borrow()
            .expectations
            .iter()
            .find(|e| e.name == name)
            .map_or(0, |e| e.calls.get())
    }

    /// Verifies every configured expectation.
    ///
    /// # Panics
    ///
    /// Panics listing every expectation whose call count was not met.
    pub fn assert_expectations(&self) {
        self.verified.set(true);
        self.spec.borrow().assert_expectations();
    }
}

impl Drop for MockContract {
    fn drop(&mut self) {
        MOCKS.with(|mocks| {
            mocks
                .borrow_mut()
                .retain(|(address, _)| address != &self.address);
        });
        // A test that already failed should report its own panic, not a
        // secondary one from an unmet expectation mid-unwind.
        if !self.verified.get() && !std::thread::panicking() {
            self.assert_expectations();
        }
    }
}

/// Decodes argument `index` of a mocked call as `T`.
///
/// # Panics
///
/// Panics if there is no argument at `index` or it does not decode as `T`.
pub fn arg<T>(env: &Env, args: &[Val], index: usize) -> T
where
    T: TryFromVal<Env, Val>,
{
    let value = args.get(index).unwrap_or_else(|| {
        panic!(
            "mock contract: argument {index} missing (call had {} argument(s))",
            args.len()
        )
    });
    T::try_from_val(env, value).unwrap_or_else(|_| {
        panic!("mock contract: argument {index} does not decode to the expected type")
    })
}

/// Dispatches an invocation to the expectation registered for `name`.
///
/// Called by the functions generated by [`mock_contract`]; not part of the
/// public API.
#[doc(hidden)]
pub fn dispatch<R>(env: &Env, name: &str, args: &[Val]) -> R
where
    R: TryFromVal<Env, Val>,
{
    let address = env.current_contract_address();
    let spec = MOCKS
        .with(|mocks| {
            mocks
                .borrow()
                .iter()
                .find(|(registered, _)| registered == &address)
                .map(|(_, spec)| Rc::clone(spec))
        })
        .unwrap_or_else(|| panic!("mock contract: no mock registered at {address:?}"));

    let result = spec.borrow_mut().invoke(env, name, args);
    match result {
        Ok(value) => R::try_from_val(env, &value).unwrap_or_else(|_| {
            panic!("mock contract: `{name}` returned a value that does not decode to the declared return type")
        }),
        Err(message) => panic!("{message}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use soroban_sdk::testutils::Address as _;
    use soroban_sdk::{contract, contractimpl, symbol_short, Address, Env, Symbol};

    #[contract]
    pub struct RateOracle;

    #[crate::mock_contract]
    #[contractimpl]
    impl RateOracle {
        pub fn get_rate(_env: Env, _asset: Address) -> i128 {
            unimplemented!("replaced by mock_contract")
        }

        pub fn label(_env: Env) -> Symbol {
            unimplemented!("replaced by mock_contract")
        }
    }

    #[contract]
    pub struct Consumer;

    #[contractimpl]
    impl Consumer {
        pub fn quote(env: Env, oracle: Address, asset: Address) -> i128 {
            RateOracleClient::new(&env, &oracle).get_rate(&asset)
        }
    }

    #[test]
    fn dispatches_multiple_functions_and_checks_arguments() {
        let env = Env::default();
        env.mock_all_auths();
        let asset = Address::generate(&env);

        let expected_asset = asset.clone();
        let oracle = MockContractBuilder::<RateOracle>::new(&env)
            .expect_call("get_rate", move |env, args| {
                let passed: Address = arg(env, args, 0);
                assert_eq!(passed, expected_asset);
                1_500i128
            })
            .times(2)
            .expect_call("label", |env, _args| Symbol::new(env, "ORACLE"))
            .build();

        let consumer = env.register(Consumer, ());
        let consumer_client = ConsumerClient::new(&env, &consumer);
        assert_eq!(consumer_client.quote(&oracle.address(), &asset), 1_500);
        assert_eq!(consumer_client.quote(&oracle.address(), &asset), 1_500);

        let oracle_client = RateOracleClient::new(&env, &oracle.address());
        assert_eq!(oracle_client.label(), symbol_short!("ORACLE"));
        assert_eq!(oracle.calls("get_rate"), 2);
        oracle.assert_expectations();
    }

    #[test]
    fn simulated_panic_fails_the_invocation() {
        let env = Env::default();
        env.mock_all_auths();
        let asset = Address::generate(&env);

        let oracle = MockContractBuilder::<RateOracle>::new(&env)
            .expect_panic("get_rate", "oracle offline")
            .times(1)
            .expect_call("label", |env, _args| Symbol::new(env, "ORACLE"))
            .never()
            .build();

        let oracle_client = RateOracleClient::new(&env, &oracle.address());
        assert!(oracle_client.try_get_rate(&asset).is_err());
        oracle.assert_expectations();
    }

    #[test]
    fn over_calling_an_expectation_fails_the_invocation() {
        let env = Env::default();
        env.mock_all_auths();
        let asset = Address::generate(&env);

        let oracle = MockContractBuilder::<RateOracle>::new(&env)
            .expect_call("get_rate", |_env, _args| 1i128)
            .times(1)
            .build();

        let oracle_client = RateOracleClient::new(&env, &oracle.address());
        assert_eq!(oracle_client.get_rate(&asset), 1);
        assert!(oracle_client.try_get_rate(&asset).is_err());
    }

    #[test]
    fn unexpected_function_reports_the_configured_ones() {
        let env = Env::default();
        let asset = Address::generate(&env);

        let oracle = MockContractBuilder::<RateOracle>::new(&env)
            .expect_call("label", |env, _args| Symbol::new(env, "ORACLE"))
            .never()
            .build();

        let oracle_client = RateOracleClient::new(&env, &oracle.address());
        assert!(oracle_client.try_get_rate(&asset).is_err());
    }
}
